const STORAGE_KEY = 'jigaku.furigana.v1';
const SETTINGS_KEY = 'edu:jigaku-coach-v1:settings';

// 長い言葉から当てる（例：「教科書」が「教科」より先）
const ENTRIES = [...DICTIONARY].sort((a, b) => b[0].length - a[0].length);
const READINGS = new Map(ENTRIES);
const PATTERN = new RegExp(
  ENTRIES.map(([surface]) => surface.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'),
  'g'
);

// ルビを付けない場所：入力欄・選択肢・既にルビが付いた場所
const SKIP_SELECTOR = 'script, style, noscript, ruby, input, textarea, select, [data-no-ruby]';

function currentGrade() {
  try {
    const grade = Number(JSON.parse(localStorage.getItem(SETTINGS_KEY) || '{}').grade);
    return grade >= 1 && grade <= 6 ? grade : 3;
  } catch (_) {
    return 3;
  }
}

function rubifyTextNode(node) {
  const text = node.nodeValue;
  if (!text || !PATTERN.test(text)) return;
  PATTERN.lastIndex = 0;
  const fragment = document.createDocumentFragment();
  let last = 0;
  let match;
  while ((match = PATTERN.exec(text)) !== null) {
    if (match.index > last) fragment.append(document.createTextNode(text.slice(last, match.index)));
    const ruby = document.createElement('ruby');
    ruby.className = 'jg-furi';
    ruby.append(document.createTextNode(match[0]));
    const rt = document.createElement('rt');
    rt.textContent = READINGS.get(match[0]);
    ruby.append(rt);
    fragment.append(ruby);
    last = match.index + match[0].length;
  }
  if (last < text.length) fragment.append(document.createTextNode(text.slice(last)));
  node.replaceWith(fragment);
}

function rubify(root) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      const parent = node.parentElement;
      if (!parent || parent.closest(SKIP_SELECTOR)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const targets = [];
  while (walker.nextNode()) targets.push(walker.currentNode);
  targets.forEach(rubifyTextNode);
}

function unwrapAll() {
  document.querySelectorAll('ruby.jg-furi').forEach((ruby) => {
    ruby.replaceWith(document.createTextNode(ruby.childNodes[0]?.textContent || ''));
  });
}

export function initFurigana(button) {
  // 1・2年生のときだけ使う。それ以外ではボタンも出さず、何もしない。
  if (currentGrade() > 2) return;
  let enabled = true;
  try {
    enabled = localStorage.getItem(STORAGE_KEY) !== 'off';
  } catch (_) { /* 保存できない環境では初期値ON */ }

  let applying = false;
  function apply() {
    if (!enabled || applying) return;
    applying = true;
    requestAnimationFrame(() => {
      rubify(document.body);
      applying = false;
    });
  }

  if (button) {
    button.hidden = false;
    const syncButton = () => {
      button.textContent = enabled ? 'ふりがな：ON' : 'ふりがな：OFF';
      button.setAttribute('aria-pressed', String(enabled));
      button.classList.toggle('is-off', !enabled);
    };
    button.addEventListener('click', () => {
      enabled = !enabled;
      try {
        localStorage.setItem(STORAGE_KEY, enabled ? 'on' : 'off');
      } catch (_) { /* 保存できなくても切り替え自体は有効 */ }
      syncButton();
      if (enabled) apply();
      else unwrapAll();
    });
    syncButton();
  }

  const observer = new MutationObserver(() => apply());
  observer.observe(document.body, { childList: true, subtree: true });
  apply();
}
